// Arrays:
// Ordered list of values.
// Accessed by index.
// Can contain duplicates.
// Can be easily iterated over.
// Example: let myArray = [1, 2, 3];
// Objects:
// Unordered collection of key-value pairs.
// Accessed by key.
// Keys must be unique.
// Keys must be explicitly iterated over.
// Example: let myObject = {a: 1, b: 2, c: 3};
// Example Program Comparing Both:


let myArray = [1, 2, 3];
let myObject = {a: 1, b: 2, c: 3};
 
console.log(myArray[1]); // Output: 2
console.log(myObject.b); // Output: 2




//In this example, myArray is accessed using an index, while myObject is accessed using a key.