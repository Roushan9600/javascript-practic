// An array is like a list of items. Each item in the list is stored at a specific position (index), starting from 0.

// Example Program:


let numbers = [1, 2, 3, 4, 5];
console.log(numbers[0]); // Output: 1
console.log(numbers[3]); // Output: 4
console.log(numbers.length); // Output: 5


//In this example, numbers is an array containing integers. You access elements by their index (e.g., numbers[0] for the first element). The length property tells you how many elements are in the array.